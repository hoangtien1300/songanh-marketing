        function calcRankChange(initRankStr, gscPosVal) {
            if (!initRankStr || gscPosVal === undefined || gscPosVal === null) return { text: '=0', color: 'text-slate-500' };
            const match = initRankStr.toString().match(/(\d+(?:\.\d+)?)/);
            if (!match) return { text: '=0', color: 'text-slate-500' };
            const initVal = parseFloat(match[1]);
            const gscVal = parseFloat(gscPosVal);
            const diff = Math.round((initVal - gscVal) * 10) / 10;
            if (diff > 0) {
                return { text: `<i class="fa-solid fa-arrow-up text-xs mr-1"></i>↑ +${diff.toFixed(1)}`, color: 'text-emerald-600' };
            } else if (diff < 0) {
                const absDiff = Math.abs(diff);
                return { text: `<i class="fa-solid fa-arrow-down text-xs mr-1"></i>↓ -${absDiff.toFixed(1)}`, color: 'text-rose-600' };
            } else {
                return { text: '=0', color: 'text-slate-500' };
            }
        }

